def tipik(segment_kodu: str, eksen: str, n: int = 1) -> list[str]:
    """Segmentte en tipik n değer (yüksek ağırlıktan düşüğe)."""
    tablo = PROFIL.get(segment_kodu, {}).get(eksen, {})
    return [d for d, _ in sorted(tablo.items(), key=lambda x: (-x[1], x[0]))[:n]]
