"""Karar ağaçları.

Her ağaç: olay türü → sorular (düğümler) → sonuç (yaprak).
Düğüm biçimi:
    {"soru": "...", "anahtar": "parametre_adi",
     "dallar": [{"etiket": "...", "kosul": [op, deger], "sonraki": "dugum_id"}, ...],
     "varsayilan": "dugum_id"}          # parametre bilinmiyorsa veya hiçbir koşul tutmazsa
Yaprak biçimi:
    {"sonuc": "...", "egilim": "olumlu|olumsuz|notr|karisik", "eylem": "...",
     "gerekce": "...", "izlenecek": [...], "etkilenen": [...]}
Koşul işleçleri: == != >= > <= < in  (deger bir liste ise "in" ile üyelik bakılır)

Ağaçlar yatırım tavsiyesi değildir; haberi okuma düzeni ve karar noktalarının haritasıdır.
"""

from __future__ import annotations

from typing import Any

Agac = dict[str, Any]


def _yaprak(sonuc: str, egilim: str, eylem: str, gerekce: str, izlenecek: list[str] | None = None,
            etkilenen: list[str] | None = None) -> dict[str, Any]:
    return {"sonuc": sonuc, "egilim": egilim, "eylem": eylem, "gerekce": gerekce,
            "izlenecek": izlenecek or [], "etkilenen": etkilenen or []}


def _dugum(soru: str, anahtar: str, dallar: list[tuple[str, list[Any] | None, str]], varsayilan: str | None = None) -> dict[str, Any]:
    return {
        "soru": soru,
        "anahtar": anahtar,
        "dallar": [{"etiket": e, "kosul": k, "sonraki": s} for e, k, s in dallar],
        "varsayilan": varsayilan or dallar[-1][2],
    }


